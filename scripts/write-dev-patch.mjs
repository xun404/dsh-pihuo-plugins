#!/usr/bin/env node
/**
 * Prepare a local web overlay:
 *   1. Symlink this checkout's packages into the web profile's node_modules
 *      so ESM `import('@pihuo/dsh-…')` and client-modules
 *      `require.resolve('<name>/package.json')` both resolve. NODE_PATH is
 *      not enough — Node ESM ignores it.
 *   2. Write a `--patch` file that uses those package names (so
 *      `__DSH_BOOT__.entries[].id` matches the client factory handoff id).
 *
 *   node scripts/write-dev-patch.mjs [outfile]
 *
 * Default outfile: /tmp/dsh-pihuo-web.patch.yml
 * Profile: $DSH_HOME/profiles/web  (default ~/.dsh/profiles/web)
 *
 * Launch:
 *   npx --yes @deepseek-ai/dsh web --patch /tmp/dsh-pihuo-web.patch.yml
 *   # or, after pnpm install && pnpm run build in the harness checkout:
 *   pnpm --dir ../deepseek-harness dsh web --patch /tmp/dsh-pihuo-web.patch.yml
 */
import { homedir } from 'node:os'
import { mkdirSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const out = process.argv[2] ?? '/tmp/dsh-pihuo-web.patch.yml'
const dshHome = process.env.DSH_HOME ?? join(homedir(), '.dsh')
const profileDir = join(dshHome, 'profiles/web')
const nodeModules = join(profileDir, 'node_modules')
const mock = join(root, 'packages/acp-protocol/bin/mock-acp-agent.mjs')

const links = {
  '@pihuo/dsh-worker-protocol': join(root, 'packages/worker-protocol'),
  '@pihuo/dsh-worker-runtime': join(root, 'packages/worker-runtime'),
  '@pihuo/dsh-acp-protocol': join(root, 'packages/acp-protocol'),
  '@pihuo/dsh-acp-worker': join(root, 'packages/acp-worker'),
  '@pihuo/dsh-ui-acp-worker': join(root, 'packages/ui-acp-worker'),
  '@pihuo/dsh-pihuo': join(root, 'packages/bundle'),
}

mkdirSync(join(nodeModules, '@pihuo'), { recursive: true })
for (const [spec, target] of Object.entries(links)) {
  const dest = join(nodeModules, spec)
  rmSync(dest, { recursive: true, force: true })
  symlinkSync(target, dest)
}

const yaml = `# Generated by scripts/write-dev-patch.mjs — do not commit.
# Rows use package names so client-modules boot ids match lib/client.js.
# Packages are symlinked into ${nodeModules}
- insert:
    - id: pihuo-acp
      name: '@pihuo/dsh-acp-worker'
      config:
        providerName: pihuo-acp
        command: node
        args:
          - ${JSON.stringify(mock)}
        permission: allow

    - id: acp-worker-tool
      name: '@deepseek-ai/dsh-tool-subagent'
      config:
        provider: pihuo-acp
        toolName: acp_worker
        maxDepth: provider-managed
        enableRunInBackground: false
        backgroundMode: one-shot

    - id: ui-acp-worker
      name: '@pihuo/dsh-ui-acp-worker'
`

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, yaml)
process.stdout.write(JSON.stringify({ patch: out, profileDir, nodeModules }, null, 2) + '\n')
